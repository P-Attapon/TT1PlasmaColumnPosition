"""Test battery for the Biot-Savart package. No repository or shot data needed.

    python -m methods_script.biot_savart.tests

T1  on-axis field against the elementary closed form   (external reference)
T2  div B = 0 and curl B = 0 off the wire              (external constraint)
T3  mirror symmetry about the loop plane
T4  recovery error against injected noise (synthetic signals)
T5  invariance of the fit to overall signal scaling
T6  trajectory tracking with the grid search
T7  behaviour on dead probes, NaNs, the Ip gate and probe subsets
"""

from __future__ import annotations

import warnings

import numpy as np

warnings.filterwarnings("ignore")

from . import adapter, field, invert  # noqa: E402

MU0 = 4.0e-7 * np.pi
GEOM = adapter.load_geometry(strict=False)
FWD = adapter.load_forward("internal", GEOM)
FWD_MANY = adapter.load_forward_many(GEOM)
TPL = invert.Templates(FWD_MANY, np.arange(12), np.ones(12), step=0.002)

_results = []


def _report(name, ok, detail):
    _results.append((name, ok))
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}: {detail}")


